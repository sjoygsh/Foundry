CELL, COLS = 8, 16
first, last = 32, 126
count = last - first + 1
rows_of_cells = (count + COLS - 1) // COLS
W, H = COLS * CELL, rows_of_cells * CELL

missing = [chr(c) for c in range(first, last + 1) if chr(c) not in G]
if missing:
    sys.exit("missing glyphs: " + repr(missing))

px = bytearray(W * H * 4)  # transparent
for i in range(count):
    ch = chr(first + i)
    cx, cy = (i % COLS) * CELL, (i // COLS) * CELL
    for r, line in enumerate(G[ch]):
        for c, v in enumerate(line):
            if v == '#':
                o = ((cy + r) * W + (cx + c)) * 4
                px[o:o+4] = b'\xff\xff\xff\xff'

raw = bytearray()
for y in range(H):
    raw.append(0)  # filter: none
    raw += px[y * W * 4:(y + 1) * W * 4]

def chunk(tag, data):
    return (struct.pack('>I', len(data)) + tag + data +
            struct.pack('>I', binascii.crc32(tag + data) & 0xFFFFFFFF))

png = (b'\x89PNG\r\n\x1a\n' +
       chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 6, 0, 0, 0)) +
       chunk(b'IDAT', zlib.compress(bytes(raw), 9)) +
       chunk(b'IEND', b''))

out = os.path.join("samples", "sandbox", "assets", "font.png")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "wb") as f:
    f.write(png)
print(f"wrote {out}, {len(png)} bytes, {W}x{H}, {count} glyphs on a {COLS}-column grid")
