};

fn indexOf(fields: Fields, field: []const u8) ?u32 {
    for (fields.fields, 0..) |candidate, i| {
        if (std.mem.eql(u8, candidate.name, field)) return @intCast(i);
    }
    return null;
}

pub fn model(fields: Fields) DecodeError!ContentId {
    const id = (try fields.idAt(indexOf(fields, "model") orelse return error.NoModel)) orelse return error.NoModel;
    if (id.isNone()) return error.NoModel;
    return id;
}

pub fn start(fields: Fields) DecodeError!?[]const u8 {
    return optionalName(fields, "start");
}

pub fn motionJoint(fields: Fields) DecodeError!?[]const u8 {
    return optionalName(fields, "motion_joint");
}

fn optionalName(fields: Fields, field: []const u8) DecodeError!?[]const u8 {
    const value = (try fields.stringAt(indexOf(fields, field) orelse return null)) orelse return null;
    if (value.len == 0) return error.EmptyName;
    return value;
}

pub fn clips(fields: Fields) DecodeError!?List {
    return fields.listAt(indexOf(fields, "clips") orelse return null);
}

/// The `index`th listed clip, its defaults in place.
pub fn clipAt(list: List, index: u32) DecodeError!Clip {
    const fields = (try list.nestedAt(index)) orelse return error.EmptyName;
    const clip_name = (try fields.stringAt(indexOf(fields, "name") orelse return error.EmptyName)) orelse return error.EmptyName;
    if (clip_name.len == 0) return error.EmptyName;
    const speed: f32 = if (indexOf(fields, "speed")) |at| @floatCast((try fields.floatAt(at)) orelse 1) else 1;
    return .{
        .name = clip_name,
        .loop = if (indexOf(fields, "loop")) |at| (try fields.boolAt(at)) orelse true else true,
        .speed = speed,
        .motion = if (indexOf(fields, "motion")) |at| (try fields.boolAt(at)) orelse false else false,
        .events = if (indexOf(fields, "events")) |at| try fields.listAt(at) else null,
    };
}

/// The `index`th event of a clip's list.
pub fn eventAt(list: List, index: u32) DecodeError!anim.Event {
    const fields = (try list.nestedAt(index)) orelse return error.UnnamedEvent;
    const at = (try fields.floatAt(indexOf(fields, "at") orelse return error.EventOutOfRange)) orelse return error.EventOutOfRange;
    const id = (try fields.idAt(indexOf(fields, "event") orelse return error.UnnamedEvent)) orelse return error.UnnamedEvent;
    if (id.isNone()) return error.UnnamedEvent;
    return .{ .at = @floatCast(at), .id = id };
}

