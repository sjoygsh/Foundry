const testing = std.testing;
const gpa = testing.allocator;

const Compiled = struct {
    registry: Registry,
    package: data.Package,
    diags: data.Diagnostics,
    bytes: std.ArrayList(u8) = .empty,
    store: data.Store,

    fn init(self: *Compiled, source: []const u8) !void {
        self.* = .{
            .registry = .init(gpa, .default),
            .package = try data.Package.init(gpa, "t:content", 1, .default),
            .diags = .init(gpa, .default),
            .store = .init(gpa, .default),
        };
        try registerAll(gpa, &self.registry);
        var doc = try data.parser.parse(gpa, "t.fdt", source, .{ .namespace = "t" }, &self.diags);
        defer doc.deinit(gpa);
        try self.package.addDocument(gpa, &doc, &self.registry, &self.diags);
        try data.fpk.write(gpa, &self.package, &self.registry, &self.bytes);
        _ = try self.store.add(gpa, "t.fpk", self.bytes.items, &self.registry, &self.diags);
    }

    fn deinit(self: *Compiled) void {
        self.store.deinit(gpa);
        self.bytes.deinit(gpa);
        self.diags.deinit(gpa);
        self.package.deinit(gpa);
        self.registry.deinit(gpa);
    }

    fn fields(self: *Compiled) Fields {
        return self.store.lookup(ContentId.fromString("t:set")).?.fields;
    }
};

test "a set reads with its defaults in place" {
    var c: Compiled = undefined;
    try c.init(
        \\foundry:animation_set t:set {
        \\    model t:model
        \\    start "idle"
        \\    motion_joint "pelvis"
        \\    clips [
        \\        { name "stride" motion true events [ { at 0.25 event t:foot } { at 0.75 event t:foot } ] }
        \\        { name "turn" loop false speed 1.5 }
        \\    ]
        \\}
    );
    defer c.deinit();
    const fields = c.fields();
    try check(fields);
    try testing.expect((try model(fields)).eql(ContentId.fromString("t:model")));
    try testing.expectEqualStrings("idle", (try start(fields)).?);
    try testing.expectEqualStrings("pelvis", (try motionJoint(fields)).?);

    const list = (try clips(fields)).?;
    const stride = try clipAt(list, 0);
    try testing.expectEqualStrings("stride", stride.name);
    try testing.expect(stride.loop and stride.motion);
    try testing.expectEqual(@as(f32, 1), stride.speed);
    const event = try eventAt(stride.events.?, 1);
    try testing.expectEqual(@as(f32, 0.75), event.at);
    try testing.expect(event.id.eql(ContentId.fromString("t:foot")));

    const turn = try clipAt(list, 1);
    try testing.expect(!turn.loop and !turn.motion);
    try testing.expectEqual(@as(f32, 1.5), turn.speed);
    try testing.expect(turn.events == null);
}

