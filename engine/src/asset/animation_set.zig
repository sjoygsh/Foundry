//! `foundry:animation_set`: what each clip of a model means (`docs/design/animation-logic.md` §4,
//! ADR-0071).
//!
//! ```fdt
//! foundry:animation_set sandbox3d:walker.set {
//!     model sandbox3d:models.walker
//!     start "idle"
//!     motion_joint "pelvis"
//!     clips [
//!         { name "stride" motion true events [
//!             { at 0.0 event sandbox3d:event.footfall }
//!             { at 0.5 event sandbox3d:event.footfall }
//!         ] }
//!         { name "turn" loop false motion true speed 1.2 }
//!     ]
//! }
//! ```
//!
//! **glTF has no loop flag, no events and no root joint, and a clip's records are generated by the
//! import.** So what a clip means can't live in the clip. It is one hand-written record a model,
//! and a mod overrides that record to retime a footstep without touching an asset.
//!
//! **A model's clip the set does not list** plays looped at speed 1, with no motion and no events.
//!
//! **`check` is what one record can show,** and `fpack` runs it. What depends on other records
//! (does the model have this clip, is this joint a root) is `rigs.zig`'s, when a rig is built,
//! since a mod may override any of them.
//!
//! **Every name here is on authors' disks** (CLAUDE.md §7).

const std = @import("std");
const anim = @import("anim");
const core = @import("core");
const data = @import("data");

const Allocator = std.mem.Allocator;
const ContentId = core.ContentId;
const Fields = data.fpk.Fields;
const FieldType = data.FieldType;
const List = data.fpk.List;
const Registry = data.Registry;
const Schema = data.Schema;
const SchemaId = data.SchemaId;

pub const name = "foundry:animation_set";

/// Clips one set may say something about.
pub const max_clips: usize = 256;
pub const max_events: usize = anim.max_clip_events;

const event_type: FieldType = .{ .nested = &.{
    .{ .name = "at", .type = .f32 },
    .{ .name = "event", .type = .id },
} };

const clip_type: FieldType = .{ .nested = &.{
    .{ .name = "name", .type = .string },
    .{ .name = "loop", .type = .bool, .presence = .{ .default = .{ .bool = true } } },
    .{ .name = "speed", .type = .f32, .presence = .{ .default = .{ .float = 1 } } },
    .{ .name = "motion", .type = .bool, .presence = .{ .default = .{ .bool = false } } },
    .{ .name = "events", .type = .{ .list = &event_type }, .presence = .optional },
} };

pub const schema: Schema = .{
    .id = SchemaId.fromStringUnchecked(name),
    .version = 1,
    .fields = &.{
        .{ .name = "model", .type = .id },
        .{ .name = "start", .type = .string, .presence = .optional },
        .{ .name = "motion_joint", .type = .string, .presence = .optional },
        .{ .name = "clips", .type = .{ .list = &clip_type }, .presence = .optional },
    },
};

pub fn registerAll(allocator: Allocator, registry: *Registry) (data.schema.RegisterError || Allocator.Error)!void {
    _ = try registry.register(allocator, schema);
}

pub const Refusal = error{
    NoModel,
    EmptyName,
    TooManyClips,
    DuplicateClip,
    InvalidSpeed,
    TooManyEvents,
    UnnamedEvent,
    EventOutOfRange,
    UnsortedEvents,
    MissingMotionJoint,
};

pub const DecodeError = Refusal || data.fpk.ReadError;

/// What a diagnostic says, after the record's name.
pub fn describe(err: DecodeError) []const u8 {
    return switch (err) {
        error.NoModel => "names no model",
        error.EmptyName => "has an empty clip or joint name",
        error.TooManyClips => "lists more clips than a set may hold, 256",
        error.DuplicateClip => "lists one clip twice",
        error.InvalidSpeed => "has a clip whose speed is not above 0 and at most 16",
        error.TooManyEvents => "has a clip with more than 64 events",
        error.UnnamedEvent => "has an event with no id",
        error.EventOutOfRange => "has an event outside its clip: 'at' is from 0 to under 1, or exactly 1 on a clip that does not loop",
        error.UnsortedEvents => "has a clip whose events are not in order of 'at'",
        error.MissingMotionJoint => "has a clip with motion, and no motion_joint",
        else => "is malformed",
    };
}

pub const Clip = struct {
    name: []const u8,
    loop: bool,
    speed: f32,
    motion: bool,
    events: ?List,
};

fn indexOf(fields: Fields, field: []const u8) ?u32 {
    for (fields.fields, 0..) |candidate, i| {
        if (std.mem.eql(u8, candidate.name, field)) return @intCast(i);
    }
    return null;
}

pub fn model(fields: Fields) DecodeError!ContentId {
    const id = (try fields.idAt(indexOf(fields, "model") orelse return error.NoModel)) orelse return error.NoModel;
    if (id.isNone()) return error.NoModel;
    return id;
}

pub fn start(fields: Fields) DecodeError!?[]const u8 {
    return optionalName(fields, "start");
}

pub fn motionJoint(fields: Fields) DecodeError!?[]const u8 {
    return optionalName(fields, "motion_joint");
}

fn optionalName(fields: Fields, field: []const u8) DecodeError!?[]const u8 {
    const value = (try fields.stringAt(indexOf(fields, field) orelse return null)) orelse return null;
    if (value.len == 0) return error.EmptyName;
    return value;
}

pub fn clips(fields: Fields) DecodeError!?List {
    return fields.listAt(indexOf(fields, "clips") orelse return null);
}

/// The `index`th listed clip, its defaults in place.
pub fn clipAt(list: List, index: u32) DecodeError!Clip {
    const fields = (try list.nestedAt(index)) orelse return error.EmptyName;
    const clip_name = (try fields.stringAt(indexOf(fields, "name") orelse return error.EmptyName)) orelse return error.EmptyName;
    if (clip_name.len == 0) return error.EmptyName;
    const speed: f32 = if (indexOf(fields, "speed")) |at| @floatCast((try fields.floatAt(at)) orelse 1) else 1;
    return .{
        .name = clip_name,
        .loop = if (indexOf(fields, "loop")) |at| (try fields.boolAt(at)) orelse true else true,
        .speed = speed,
        .motion = if (indexOf(fields, "motion")) |at| (try fields.boolAt(at)) orelse false else false,
        .events = if (indexOf(fields, "events")) |at| try fields.listAt(at) else null,
    };
}

/// The `index`th event of a clip's list.
pub fn eventAt(list: List, index: u32) DecodeError!anim.Event {
    const fields = (try list.nestedAt(index)) orelse return error.UnnamedEvent;
    const at = (try fields.floatAt(indexOf(fields, "at") orelse return error.EventOutOfRange)) orelse return error.EventOutOfRange;
    const id = (try fields.idAt(indexOf(fields, "event") orelse return error.UnnamedEvent)) orelse return error.UnnamedEvent;
    if (id.isNone()) return error.UnnamedEvent;
    return .{ .at = @floatCast(at), .id = id };
}

/// Everything one record can show. It allocates nothing, so a package's compile can run it.
pub fn check(fields: Fields) DecodeError!void {
    _ = try model(fields);
    _ = try start(fields);
    const joint = try motionJoint(fields);
    const list = (try clips(fields)) orelse return;
    if (list.len > max_clips) return error.TooManyClips;
    for (0..list.len) |i| {
        const clip = try clipAt(list, @intCast(i));
        for (0..i) |earlier| {
            if (std.mem.eql(u8, (try clipAt(list, @intCast(earlier))).name, clip.name)) return error.DuplicateClip;
        }
        // Written so a NaN is refused.
        if (!(clip.speed > 0 and clip.speed <= anim.max_speed)) return error.InvalidSpeed;
        if (clip.motion and joint == null) return error.MissingMotionJoint;
        const events = clip.events orelse continue;
        if (events.len > max_events) return error.TooManyEvents;
        var previous: f32 = 0;
        for (0..events.len) |e| {
            const event = try eventAt(events, @intCast(e));
            const inside = event.at >= 0 and (event.at < 1 or (event.at == 1 and !clip.loop));
            if (!inside) return error.EventOutOfRange;
            if (event.at < previous) return error.UnsortedEvents;
            previous = event.at;
        }
    }
}

// -- tests -----------------------------------------------------------------------------

const testing = std.testing;
const gpa = testing.allocator;

const Compiled = struct {
    registry: Registry,
    package: data.Package,
    diags: data.Diagnostics,
    bytes: std.ArrayList(u8) = .empty,
    store: data.Store,

    fn init(self: *Compiled, source: []const u8) !void {
        self.* = .{
            .registry = .init(gpa, .default),
            .package = try data.Package.init(gpa, "t:content", 1, .default),
            .diags = .init(gpa, .default),
            .store = .init(gpa, .default),
        };
        try registerAll(gpa, &self.registry);
        var doc = try data.parser.parse(gpa, "t.fdt", source, .{ .namespace = "t" }, &self.diags);
        defer doc.deinit(gpa);
        try self.package.addDocument(gpa, &doc, &self.registry, &self.diags);
        try data.fpk.write(gpa, &self.package, &self.registry, &self.bytes);
        _ = try self.store.add(gpa, "t.fpk", self.bytes.items, &self.registry, &self.diags);
    }

    fn deinit(self: *Compiled) void {
        self.store.deinit(gpa);
        self.bytes.deinit(gpa);
        self.diags.deinit(gpa);
        self.package.deinit(gpa);
        self.registry.deinit(gpa);
    }

    fn fields(self: *Compiled) Fields {
        return self.store.lookup(ContentId.fromString("t:set")).?.fields;
    }
};

test "a set reads with its defaults in place" {
    var c: Compiled = undefined;
    try c.init(
        \\foundry:animation_set t:set {
        \\    model t:model
        \\    start "idle"
        \\    motion_joint "pelvis"
        \\    clips [
        \\        { name "stride" motion true events [ { at 0.25 event t:foot } { at 0.75 event t:foot } ] }
        \\        { name "turn" loop false speed 1.5 }
        \\    ]
        \\}
    );
    defer c.deinit();
    const fields = c.fields();
    try check(fields);
    try testing.expect((try model(fields)).eql(ContentId.fromString("t:model")));
    try testing.expectEqualStrings("idle", (try start(fields)).?);
    try testing.expectEqualStrings("pelvis", (try motionJoint(fields)).?);

    const list = (try clips(fields)).?;
    const stride = try clipAt(list, 0);
    try testing.expectEqualStrings("stride", stride.name);
    try testing.expect(stride.loop and stride.motion);
    try testing.expectEqual(@as(f32, 1), stride.speed);
    const event = try eventAt(stride.events.?, 1);
    try testing.expectEqual(@as(f32, 0.75), event.at);
    try testing.expect(event.id.eql(ContentId.fromString("t:foot")));

    const turn = try clipAt(list, 1);
    try testing.expect(!turn.loop and !turn.motion);
    try testing.expectEqual(@as(f32, 1.5), turn.speed);
    try testing.expect(turn.events == null);
}

test "a set may be no more than a model" {
    var c: Compiled = undefined;
    try c.init("foundry:animation_set t:set { model t:model }");
    defer c.deinit();
    try check(c.fields());
    try testing.expect((try start(c.fields())) == null);
    try testing.expect((try clips(c.fields())) == null);
}

fn expectRefused(expected: DecodeError, source: []const u8) !void {
    var c: Compiled = undefined;
    try c.init(source);
    defer c.deinit();
    try testing.expectError(expected, check(c.fields()));
    try testing.expect(!std.mem.eql(u8, describe(expected), "is malformed"));
}

test "every refusal is named, at its boundary" {
    try expectRefused(error.EmptyName, "foundry:animation_set t:set { model t:m start \"\" }");
    try expectRefused(error.EmptyName, "foundry:animation_set t:set { model t:m motion_joint \"\" }");
    try expectRefused(error.EmptyName, "foundry:animation_set t:set { model t:m clips [ { name \"\" } ] }");
    try expectRefused(error.DuplicateClip, "foundry:animation_set t:set { model t:m clips [ { name \"a\" } { name \"b\" } { name \"a\" } ] }");
    try expectRefused(error.InvalidSpeed, "foundry:animation_set t:set { model t:m clips [ { name \"a\" speed 0 } ] }");
    try expectRefused(error.InvalidSpeed, "foundry:animation_set t:set { model t:m clips [ { name \"a\" speed 16.5 } ] }");
    try expectRefused(error.MissingMotionJoint, "foundry:animation_set t:set { model t:m clips [ { name \"a\" motion true } ] }");
    try expectRefused(error.EventOutOfRange, "foundry:animation_set t:set { model t:m clips [ { name \"a\" events [ { at -0.1 event t:e } ] } ] }");
    try expectRefused(error.EventOutOfRange, "foundry:animation_set t:set { model t:m clips [ { name \"a\" events [ { at 1 event t:e } ] } ] }");
    try expectRefused(error.EventOutOfRange, "foundry:animation_set t:set { model t:m clips [ { name \"a\" loop false events [ { at 1.5 event t:e } ] } ] }");
    try expectRefused(error.UnsortedEvents, "foundry:animation_set t:set { model t:m clips [ { name \"a\" events [ { at 0.5 event t:e } { at 0.25 event t:e } ] } ] }");

    // 1 is a one-shot's end, and that is legal.
    var c: Compiled = undefined;
    try c.init("foundry:animation_set t:set { model t:m clips [ { name \"a\" loop false events [ { at 1 event t:e } ] } ] }");
    defer c.deinit();
    try check(c.fields());
}

test "the two limits are refused one past them" {
    var clip_text: std.ArrayList(u8) = .empty;
    defer clip_text.deinit(gpa);
    try clip_text.appendSlice(gpa, "foundry:animation_set t:set { model t:m clips [");
    for (0..max_clips + 1) |i| try clip_text.print(gpa, " {{ name \"c{d}\" }}", .{i});
    try clip_text.appendSlice(gpa, " ] }");
    try expectRefused(error.TooManyClips, clip_text.items);

    var event_text: std.ArrayList(u8) = .empty;
    defer event_text.deinit(gpa);
    try event_text.appendSlice(gpa, "foundry:animation_set t:set { model t:m clips [ { name \"a\" events [");
    for (0..max_events + 1) |_| try event_text.appendSlice(gpa, " { at 0 event t:e }");
    try event_text.appendSlice(gpa, " ] } ] }");
    try expectRefused(error.TooManyEvents, event_text.items);
}
